// 检测浏览器首选语言；中文（含简/繁体）→ zh，其余 → en。
function detectLocale() {
  const saved = localStorage.getItem('locale');
  if (saved === 'zh' || saved === 'en') return saved;
  const lang = (navigator.language || '').toLowerCase();
  return lang.startsWith('zh') ? 'zh' : 'en';
}

export const locale = ref(detectLocale());

export function setLocale(l) {
  if (l !== 'zh' && l !== 'en') return;
  locale.value = l;
  localStorage.setItem('locale', l);
}

// 翻译函数：t('key', p1, p2, ...)，占位符 {0}、{1}... 按顺序替换
export function t(key, ...params) {
  const dict = messages[locale.value] || messages.en;
  let text = dict[key];
  if (text === undefined) {
    text = messages.en[key];
    if (text === undefined) return key;
  }
  if (params.length) {
    return text.replace(/\{(\d+)\}/g, (_, i) => {
      const v = params[Number(i)];
      return v === undefined || v === null ? '' : String(v);
    });
  }
  return text;
}

export function getLocale() {
  return locale;
}
